const byLevelThenName = (a: CatalogEntry, b: CatalogEntry): number =>
  a.level - b.level || a.name.localeCompare(b.name)

export const DEFAULT_CATALOG: readonly CatalogEntry[] = MERCHANT_TYPES.flatMap((merchant) =>
  DRAFTS[merchant]
    .map(({ slug, ...entry }) => ({ ...entry, id: `${merchant}.${slug}`, merchant }))
    .sort(byLevelThenName),
)

export const catalogFor = (
  type: MerchantType,
  catalog: readonly CatalogEntry[] = DEFAULT_CATALOG,
): CatalogEntry[] => catalog.filter((entry) => entry.merchant === type).sort(byLevelThenName)

export const unlockedServices = (
  type: MerchantType,
  level: number,
  catalog: readonly CatalogEntry[] = DEFAULT_CATALOG,
): CatalogEntry[] => catalogFor(type, catalog).filter((entry) => entry.level <= level)

/** The entries at the lowest level above `level` that unlocks anything; empty when none remain. */
export function nextUnlocks(
  type: MerchantType,
  level: number,
  catalog: readonly CatalogEntry[] = DEFAULT_CATALOG,
): CatalogEntry[] {
  const locked = catalogFor(type, catalog).filter((entry) => entry.level > level)
  return locked.filter((entry) => entry.level === locked[0]?.level)
}
